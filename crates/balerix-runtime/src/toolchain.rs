/// This repository's own pins, embedded at build time so a fresh install can
/// launch `claude` without the user writing a system tool table first.
pub const EMBEDDED_MISE_TOML: &str = include_str!("../../../mise.toml");

/// Tools an agent inherits from the embedded table. `gh` is only emitted
/// when the crew authenticates through it.
const INHERITED: &[&str] = &["claude", "gh"];

fn tools_table(toml_text: &str) -> Result<BTreeMap<String, String>, String> {
    let doc: toml::Table = toml_text
        .parse()
        .map_err(|e: toml::de::Error| e.to_string())?;
    let mut out = BTreeMap::new();
    if let Some(toml::Value::Table(tools)) = doc.get("tools") {
        for (k, v) in tools {
            let version = match v {
                toml::Value::String(s) => s.clone(),
                toml::Value::Table(t) => match t.get("version") {
                    Some(toml::Value::String(s)) => s.clone(),
                    _ => return Err(format!("tools.{k}: expected a version string")),
                },
                _ => return Err(format!("tools.{k}: expected a version string")),
            };
            out.insert(k.clone(), version);
        }
    }
    Ok(out)
}

pub fn embedded_system_tools() -> BTreeMap<String, String> {
    tools_table(EMBEDDED_MISE_TOML)
        .unwrap_or_default()
        .into_iter()
        .filter(|(k, _)| INHERITED.contains(&k.as_str()))
        .collect()
}

/// `$XDG_CONFIG_HOME/balerix/mise.toml` `[tools]` if the file exists, else
/// the embedded default.
pub fn system_tools(
    layout: &StateLayout,
    id: &str,
) -> Result<BTreeMap<String, String>, MaterializeError> {
    let path = layout.system_mise_toml();
    match std::fs::read_to_string(&path) {
        Ok(text) => tools_table(&text).map_err(|message| MaterializeError::Io {
            id: id.to_string(),
            path,
            message,
        }),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(embedded_system_tools()),
        Err(e) => Err(MaterializeError::Io {
            id: id.to_string(),
            path,
            message: e.to_string(),
        }),
    }
}

/// One level's generated `mise.toml`. `label` names the owner in the header
/// comment: `agent payments/backend/alice`, `fleet payments`, `crew
/// payments/backend`, `system`.
pub fn render_level_toml(label: &str, tools: &BTreeMap<String, String>) -> String {
    let mut out =
        format!("# generated by balerix for {label}; edit the fleet file, not this\n[tools]\n");
    for (k, v) in tools {
        out.push_str(&format!("{} = {:?}\n", toml_key(k), v));
    }
    out
}

/// System ⊕ user ⊕, when `with_gh`, `gh = <balerix's pinned gh>` (spec §4.2
/// step 3): a `git.auth: gh` crew always gets a `gh` entry even if an
/// admin's system table omits one, falling back to the embedded pin; system
/// and user values still win over that fallback. Without `with_gh` the
/// *system* `gh` is dropped — a `gh` the user asked for in `settings.tools`
/// is merged in afterwards and always survives, since a crew that does not
/// use gh for git auth may still want the CLI.
pub fn render_mise_toml(
    id: &AgentId,
    system: &BTreeMap<String, String>,
    user: &BTreeMap<String, String>,
    with_gh: bool,
) -> String {
    let mut table: BTreeMap<&str, &str> = system
        .iter()
        .map(|(k, v)| (k.as_str(), v.as_str()))
        .collect();
    if !with_gh {
        table.remove("gh");
    }
    for (k, v) in user {
        table.insert(k, v);
    }
    let embedded_gh = embedded_system_tools().get("gh").cloned();
    if with_gh
        && !table.contains_key("gh")
        && let Some(pin) = &embedded_gh
    {
        table.insert("gh", pin.as_str());
    }
    let owned: BTreeMap<String, String> = table
        .into_iter()
        .map(|(k, v)| (k.to_string(), v.to_string()))
        .collect();
    render_level_toml(&format!("agent {id}"), &owned)
}

fn toml_key(k: &str) -> String {
    if k.chars()
        .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
    {
        k.to_string()
    } else {
        format!("{k:?}")
    }
}

/// The daemon-side environment for an agent's own `mise install`: the same
/// private data dir and pool chain the sandbox will use, so what the daemon
/// installs is exactly what the agent resolves.
pub fn mise_env(
    id: &AgentId,
    paths: &AgentPaths,
    layout: &StateLayout,
) -> BTreeMap<String, String> {
    let s = |p: std::path::PathBuf| p.display().to_string();
    BTreeMap::from([
        (
            "MISE_GLOBAL_CONFIG_FILE".to_string(),
            s(paths.mise_toml.clone()),
        ),
        ("MISE_DATA_DIR".to_string(), s(paths.mise_data_dir())),
        (
            "MISE_SHARED_INSTALL_DIRS".to_string(),
            layout.shared_install_dirs(id),
        ),
        ("MISE_CONFIG_DIR".to_string(), s(paths.mise_config_dir())),
        ("MISE_STATE_DIR".to_string(), s(paths.mise_state_dir())),
        ("MISE_CACHE_DIR".to_string(), s(paths.mise_cache_dir())),
        ("MISE_YES".to_string(), "1".to_string()),
        ("MISE_QUIET".to_string(), "1".to_string()),
        // never install from inside the sandbox; the daemon installs beforehand
        ("MISE_AUTO_INSTALL".to_string(), "false".to_string()),
    ])
}

/// What the daemon's install for one agent may reach
/// (`sandbox::render_mise_profile`). Read: the system prefixes, the
/// `mise` binary (canonical, as in `balerix_grants`), the agent's
/// generated `mise.toml` and the pools it resolves through (crew, fleet,
/// daemon), which mise reads and never writes. Read-write: the agent's
/// `home/`, where its four mise directories are, and the install's own
/// `$HOME` (`AgentPaths::mise_install_home`). `home/` rather than the four
/// directories below it: the agent can replace any directory under
/// `home/` with a link, and nono would grant a link's target, while
/// `home/` itself sits in the agent root, which no sandbox can write. A
/// link under `home/` pointing anywhere else resolves outside the grant
/// and the write is refused.
pub fn agent_install_grants(
    id: &AgentId,
    paths: &AgentPaths,
    layout: &StateLayout,
    mise: &Path,
) -> Grants {
    let mut read: Vec<PathBuf> = SYSTEM_READ.iter().map(PathBuf::from).collect();
    read.push(std::fs::canonicalize(mise).unwrap_or_else(|_| mise.to_path_buf()));
    read.push(paths.mise_toml.clone());
    read.extend(layout.agent_pools(id));
    Grants {
        read,
        allow: vec![paths.home.clone(), paths.mise_install_home()],
    }
}

/// The install profile for one agent, before the socket policy:
/// `agent_install_grants`, and `mise_env` with the install's own `$HOME`
/// (`install_env`).
pub fn agent_install_profile(
    id: &AgentId,
    paths: &AgentPaths,
    layout: &StateLayout,
    mise: &Path,
) -> serde_json::Value {
    render_mise_profile(
        &format!("balerix-mise-{}-{}-{}", id.fleet, id.crew, id.agent),
        &format!("generated by balerix for its own mise install for {id}"),
        &agent_install_grants(id, paths, layout, mise),
        &install_env(&mise_env(id, paths, layout), &paths.mise_install_home()),
    )
}

/// The environment of a sandboxed install: `mise` as `vars` set it, with
/// `$HOME` and `$TMPDIR` in `home`, where an installer's own caches (the
/// sigstore trust root, an npm cache) go. Nothing the daemon inherited.
pub fn install_env(vars: &BTreeMap<String, String>, home: &Path) -> BTreeMap<String, String> {
    let mut env = vars.clone();
    env.insert("HOME".into(), home.display().to_string());
    env.insert("TMPDIR".into(), home.join("tmp").display().to_string());
    env
}

/// One profile of a sandboxed install: where it is written and what it
/// says, before the socket policy.
pub(crate) struct InstallProfile<'a> {
    pub path: &'a Path,
    pub profile: serde_json::Value,
}

/// Where one sandboxed install runs: nono's `$HOME` (a `ScratchHome`
/// beside `nono_home`), the install's own `$HOME`, the logs. Shared by
/// agents (`Toolchain::install`) and plugins (`plugin::install_plugin_tools`).
pub(crate) struct SandboxedInstall<'a> {
    pub tools: &'a ToolPaths,
    pub policy: SocketPolicy,
    pub id: &'a AgentId,
    pub nono_home: &'a Path,
    pub install_home: &'a Path,
    pub logs: &'a Path,
}

impl SandboxedInstall<'_> {
    fn io(&self, path: &Path, e: impl std::fmt::Display) -> MaterializeError {
        MaterializeError::Io {
            id: self.id.to_string(),
            path: path.to_path_buf(),
            message: e.to_string(),
        }
    }

    /// `mise trust <config>` under `trust`, then `mise install` under
    /// `install` (the same profile for an agent; a plugin's are two),
    /// each call a sandbox start of its own, with the install's `$HOME`
    /// made empty before and removed after. Each profile is written
    /// under the socket policy and validated when its bytes changed.
    /// Fails closed: where nono cannot run, or the sandbox cannot start,
    /// nothing is installed.
    pub(crate) fn run(
        &self,
        trust: InstallProfile<'_>,
        install: InstallProfile<'_>,
        config: &Path,
    ) -> Result<(), MaterializeError> {
        std::fs::create_dir_all(self.logs).map_err(|e| self.io(self.logs, e))?;
        // the homes a SIGKILLed daemon could not remove
        sweep_stale_homes_beside(self.nono_home);
        self.write_profile(trust.path, trust.profile)?;
        self.write_profile(install.path, install.profile)?;
        let _home =
            InstallHome::new(self.install_home).map_err(|e| self.io(self.install_home, e))?;
        self.mise(trust.path, &["trust", &config.display().to_string()])?;
        match self.mise(install.path, &["install"]) {
            Ok(()) => Ok(()),
            Err(e) if self.nothing_missing(install.path) => {
                // mise also rewrites a tool's runtime links (`latest`, the
                // version prefixes, from 2026.10 `global`) in every install
                // directory it resolves through, the pools included, and
                // fails when it may not; the sandbox refusing those writes
                // is the point, and the tools are all there
                tracing::info!(
                    id = %self.id,
                    error = %e,
                    "mise install failed, but every tool it names is installed; \
                     a write it wanted outside the install's grants was refused"
                );
                Ok(())
            }
            Err(e) => Err(e),
        }
    }

    /// `profile` under the socket policy at `path`, validated when its
    /// bytes changed.
    fn write_profile(
        &self,
        path: &Path,
        profile: serde_json::Value,
    ) -> Result<(), MaterializeError> {
        let profile = apply_to_profile(profile, self.policy, &[], &self.tools.balerix);
        if write_profile_at(self.id, path, &profile)? {
            let home = self.scratch()?;
            validate_profile_at(
                self.tools,
                self.id,
                path,
                home.path(),
                &self.logs.join("nono.validate.log"),
            )?;
        }
        Ok(())
    }

    fn scratch(&self) -> Result<ScratchHome, MaterializeError> {
        ScratchHome::beside(self.nono_home, ".nono-mise-").map_err(|e| {
            self.io(
                self.nono_home,
                format!("cannot create nono's home beside it: {e}"),
            )
        })
    }

    /// nono's words up to and including the `--`, then the socket
    /// policy's wrapper.
    fn nono_args(&self, profile: &Path) -> Vec<String> {
        let mut args: Vec<String> = vec![
            "-s".into(),
            "--log-file".into(),
            self.logs.join("nono-mise.log").display().to_string(),
            "run".into(),
            "--no-audit".into(),
            "--profile".into(),
            profile.display().to_string(),
            "--".into(),
        ];
        args.extend(wrap_command(self.policy, &self.tools.balerix, Vec::new()));
        args
    }

    fn nono(&self, home: &ScratchHome, profile: &Path) -> Cmd {
        Cmd::new(&self.tools.nono)
            .env_clear()
            .env("HOME", home.path().display().to_string())
            .env("PATH", outer_path(self.tools))
            // as before the sandbox: no project `mise.toml` on the way up
            .cwd(Path::new("/"))
            .args(self.nono_args(profile))
    }

    /// One `mise <args>` under `profile`, logged to `mise.toolchain.log`.
    /// A failure is reported as mise's, as an unsandboxed one was; when
    /// `/bin/true` cannot start under the same profile either, it says
    /// the sandbox did not start and names nono's log.
    fn mise(&self, profile: &Path, args: &[&str]) -> Result<(), MaterializeError> {
        let home = self.scratch()?;
        let cmd = self
            .nono(&home, profile)
            .args([self.tools.mise.display().to_string()])
            .args(args.iter().copied())
            .log(&self.logs.join("mise.toolchain.log"));
        let Err(f) = cmd.run() else {
            return Ok(());
        };
        let stderr = if self.sandbox_starts(profile) {
            f.stderr
        } else {
            format!(
                "the sandbox did not start (see {}): {}",
                self.logs.join("nono-mise.log").display(),
                f.stderr
            )
        };
        Err(MaterializeError::Tool {
            id: self.id.to_string(),
            tool: "mise".into(),
            subcommand: args.first().copied().unwrap_or_default().to_string(),
            args: f.args,
            stderr,
        })
    }

    /// Whether `mise install --dry-run-code` under `profile` finds nothing
    /// to install: every tool the table names is in the data dir or a
    /// pool it resolves through.
    fn nothing_missing(&self, profile: &Path) -> bool {
        let Ok(home) = self.scratch() else {
            return false;
        };
        self.nono(&home, profile)
            .args([self.tools.mise.display().to_string()])
            .args(["install", "--dry-run-code"])
            .log(&self.logs.join("mise.toolchain.log"))
            .run()
            .is_ok()
    }

    /// Whether `/bin/true` runs under `profile`: asked once a call has
    /// failed, to tell mise's failure from the sandbox's.
    fn sandbox_starts(&self, profile: &Path) -> bool {
        let Ok(home) = self.scratch() else {
            return false;
        };
        self.nono(&home, profile)
            .args(["/bin/true"])
            .timeout(SANDBOX_START_DEADLINE)
            .run()
            .is_ok()
    }
}

/// The most `SandboxedInstall::sandbox_starts` waits for `/bin/true`.
const SANDBOX_START_DEADLINE: Duration = Duration::from_secs(10);

/// The install's own `$HOME`: emptied and made (0700, with `tmp/`) when
/// the install starts, removed when it ends, success or failure. Under
/// the agent's or plugin's root, which the daemon alone writes, so the
/// path cannot be a link; what the installer left inside is removed
/// without following any link in it.
struct InstallHome<'a>(&'a Path);

impl<'a> InstallHome<'a> {
    fn new(path: &'a Path) -> std::io::Result<Self> {
        use std::os::unix::fs::DirBuilderExt;
        match std::fs::remove_dir_all(path) {
            Ok(()) => {}
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
            Err(e) => return Err(e),
        }
        std::fs::DirBuilder::new().mode(0o700).create(path)?;
        std::fs::DirBuilder::new()
            .mode(0o700)
            .create(path.join("tmp"))?;
        Ok(Self(path))
    }
}

impl Drop for InstallHome<'_> {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(self.0);
    }
}

/// The daemon-side mise environment for one pool: read `config`, install
/// into `pool`, resolve through `parents` (read-only). Empty `parents`
/// leaves `MISE_SHARED_INSTALL_DIRS` unset rather than empty — the daemon
/// pool is the root of the chain and has nothing to fall back to.
///
/// `MISE_CONFIG_DIR`, `MISE_STATE_DIR` and `MISE_CACHE_DIR` are pinned under
/// `pool` rather than left to mise's default (which falls back to the
/// ambient `$HOME`, i.e. whatever user runs the daemon). A pool install must
/// be fully determined by the layout alone — nothing in `balerix-runtime`
/// reads the process environment — and concurrent pool installs that shared
/// a `$HOME`-derived cache/state dir were observed to race each other
/// (spurious `mise where`/`mise install` failures under load). Only
/// `pool.join("installs")` is ever exported to a child pool via
/// `MISE_SHARED_INSTALL_DIRS`, so these extra subdirectories are harmless.
pub fn level_env(config: &Path, pool: &Path, parents: &[PathBuf]) -> BTreeMap<String, String> {
    let mut env = BTreeMap::from([
        (
            "MISE_GLOBAL_CONFIG_FILE".to_string(),
            config.display().to_string(),
        ),
        ("MISE_DATA_DIR".to_string(), pool.display().to_string()),
        (
            "MISE_CONFIG_DIR".to_string(),
            pool.join("config").display().to_string(),
        ),
        (
            "MISE_STATE_DIR".to_string(),
            pool.join("state").display().to_string(),
        ),
        (
            "MISE_CACHE_DIR".to_string(),
            pool.join("cache").display().to_string(),
        ),
        ("MISE_YES".to_string(), "1".to_string()),
        ("MISE_QUIET".to_string(), "1".to_string()),
        ("MISE_AUTO_INSTALL".to_string(), "false".to_string()),
    ]);
    if !parents.is_empty() {
        env.insert("MISE_SHARED_INSTALL_DIRS".to_string(), shared_list(parents));
    }
    env
}

pub struct Toolchain<'a> {
    pub tools: &'a ToolPaths,
    pub layout: &'a StateLayout,
}

impl Toolchain<'_> {
    /// `mise <args>` against `env`, unsandboxed, with `cwd=/` so no project
    /// `mise.toml` on the way up is discovered — only the caller's own
    /// global file counts. For the pools only (`install_level`): they
    /// write only directories the daemon owns and no sandboxed process can
    /// write. An agent's own install runs sandboxed (`install`).
    fn run_mise(
        &self,
        id: &str,
        env: &BTreeMap<String, String>,
        log: &Path,
        args: &[&str],
        timeout: Option<Duration>,
    ) -> Result<(), MaterializeError> {
        let mut cmd = Cmd::new(&self.tools.mise)
            .args(args.iter().copied())
            .envs(env)
            .cwd(Path::new("/"))
            .log(log);
        if let Some(d) = timeout {
            cmd = cmd.timeout(d);
        }
        cmd.run().map(|_| ()).map_err(|f| MaterializeError::Tool {
            id: id.to_string(),
            tool: f.tool,
            subcommand: f.subcommand,
            args: f.args,
            stderr: f.stderr,
        })
    }

    /// Writes `mise.toml`; returns whether its content changed.
    pub fn write(
        &self,
        id: &AgentId,
        paths: &AgentPaths,
        system: &BTreeMap<String, String>,
        user: &BTreeMap<String, String>,
        with_gh: bool,
    ) -> Result<bool, MaterializeError> {
        let text = render_mise_toml(id, system, user, with_gh);
        if std::fs::read_to_string(&paths.mise_toml).ok().as_deref() == Some(text.as_str()) {
            return Ok(false);
        }
        write_atomic(&paths.mise_toml, text.as_bytes(), 0o644).map_err(|e| {
            MaterializeError::Io {
                id: id.to_string(),
                path: paths.mise_toml.clone(),
                message: e.to_string(),
            }
        })?;
        Ok(true)
    }

    /// `mise trust` then `mise install` of the agent's table into its own
    /// data dir, resolving through the pools, each inside nono under the
    /// install profile (`agent_install_grants`, written to
    /// `AgentPaths::mise_profile`) from an empty environment
    /// (`install_env` over `mise_env`). mise makes its directories under
    /// `home/` by path, and the agent can write `home/`: under the
    /// sandbox a link it left there cannot carry a write anywhere outside
    /// the agent's own directories. `cwd=/` so no project `mise.toml` on
    /// the way up (the repo balerix itself sits in, during tests) is
    /// discovered: only the agent's global file counts.
    pub fn install(
        &self,
        id: &AgentId,
        paths: &AgentPaths,
        policy: SocketPolicy,
    ) -> Result<(), MaterializeError> {
        // `home/` must exist for nono to grant it, and the directories
        // mise would make by path are made here without following links
        crate::home::ensure_mise_dirs(id, paths)?;
        let profile = agent_install_profile(id, paths, self.layout, &self.tools.mise);
        let path = paths.mise_profile();
        SandboxedInstall {
            tools: self.tools,
            policy,
            id,
            nono_home: &paths.nono_home,
            install_home: &paths.mise_install_home(),
            logs: &paths.logs,
        }
        .run(
            InstallProfile {
                path: &path,
                profile: profile.clone(),
            },
            InstallProfile {
                path: &path,
                profile,
            },
            &paths.mise_toml,
        )
    }

    /// Installs one level's tools into its own pool. Computes the digest of
    /// the level's rendered table and returns early — writing nothing —
    /// when `marker` already holds it; only then is `toml_path` written,
    /// `mise trust` + `mise install` run against `pool` with `parents` as
    /// read-only fallbacks, and the marker written on success. `timeout`
    /// bounds each `mise` call when set; only the system pool's caller
    /// passes one (Spec F §6) — a wedged `mise install` there must not hang
    /// the daemon forever, while the fleet and crew levels stay unbounded.
    /// `cwd=/` for the same reason `install` uses it: no project
    /// `mise.toml` on the way up may be discovered.
    #[allow(clippy::too_many_arguments)]
    pub fn install_level(
        &self,
        crew: &str,
        label: &str,
        toml_path: &Path,
        pool: &Path,
        parents: &[PathBuf],
        marker: &Path,
        tools: &BTreeMap<String, String>,
        log: &Path,
        timeout: Option<Duration>,
    ) -> Result<(), MaterializeError> {
        let text = render_level_toml(label, tools);
        let digest = hex::encode(Sha256::digest(text.as_bytes()));
        if std::fs::read_to_string(marker).ok().as_deref() == Some(digest.as_str()) {
            return Ok(());
        }
        // The system level has no crew; passing "system" for both would
        // otherwise double up as the error id "system: system".
        let id = if crew == label {
            crew.to_string()
        } else {
            format!("{crew}: {label}")
        };
        let io = |path: &Path, e: std::io::Error| MaterializeError::Io {
            id: id.clone(),
            path: path.to_path_buf(),
            message: e.to_string(),
        };
        write_atomic(toml_path, text.as_bytes(), 0o644).map_err(|e| io(toml_path, e))?;
        let env = level_env(toml_path, pool, parents);
        self.run_mise(
            &id,
            &env,
            log,
            &["trust", &toml_path.display().to_string()],
            timeout,
        )?;
        self.run_mise(&id, &env, log, &["install"], timeout)?;
        write_atomic(marker, digest.as_bytes(), 0o644).map_err(|e| io(marker, e))
    }
}

/// Drops a marker whose pool directory is gone, so `install_level` cannot
/// short-circuit past it and report an empty directory as installed (Spec
/// F, F-5). Does nothing while the pool exists.
pub fn drop_stale_marker(id: &str, pool: &Path, marker: &Path) -> Result<(), MaterializeError> {
    if !pool.exists()
        && let Err(e) = std::fs::remove_file(marker)
        && e.kind() != std::io::ErrorKind::NotFound
    {
        return Err(MaterializeError::Io {
            id: id.to_string(),
            path: marker.to_path_buf(),
            message: e.to_string(),
        });
    }
    Ok(())
}

