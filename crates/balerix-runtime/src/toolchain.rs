    /// The agent's install profile, exactly: read the system prefixes, the
    /// mise binary, the agent's table and the three pools; write the
    /// agent's four mise directories and the call's own home, and nothing
    /// under `home/`; mise's variables and the call's home, and of the
    /// daemon's environment only the passed names.
    #[test]
    fn the_agent_install_profile_writes_only_the_agents_mise_dirs() {
        let layout = StateLayout::from_env(Path::new("/h"), |_| None);
        let paths = layout.agent(&id());
        let agent = "/h/.local/state/balerix/fleets/payments/crews/backend/agents/alice";
        let call = agent_install_call(&id(), &paths, &layout, Path::new("/opt/mise/bin/mise"));
        let profile = call.profile(Path::new("/s/home"), &no_env());
        let mut env: serde_json::Map<String, serde_json::Value> = mise_env(&id(), &paths, &layout)
            .into_iter()
            .map(|(k, v)| (k, serde_json::Value::String(v)))
            .collect();
        env.insert("HOME".into(), "/s/home".into());
        env.insert("TMPDIR".into(), "/s/home/tmp".into());
        assert_eq!(
            profile,
            serde_json::json!({
                "meta": {
                    "name": "balerix-mise-payments-backend-alice",
                    "description": "generated by balerix for its own mise install for payments/backend/alice",
                },
                "filesystem": {
                    "read": [
                        "/usr", "/lib", "/lib64", "/bin", "/etc",
                        "/opt/mise/bin/mise",
                        format!("{agent}/mise.toml"),
                        "/h/.local/state/balerix/fleets/payments/crews/backend/mise",
                        "/h/.local/state/balerix/fleets/payments/mise",
                        "/h/.local/share/balerix/mise",
                    ],
                    "allow": [
                        format!("{agent}/mise/config"),
                        format!("{agent}/mise/data"),
                        format!("{agent}/mise/state"),
                        format!("{agent}/mise/cache"),
                        "/s/home",
                    ],
                },
                "workdir": { "access": "none" },
                "environment": {
                    "allow_vars": crate::install_sandbox::PASSED_VARS,
                    "set_vars": env,
                },
                "security": { "signal_mode": "isolated" },
            })
        );
        let home = format!("{agent}/home");
        let text = profile["filesystem"].to_string();
        assert!(!text.contains(&home), "nothing under home/: {text}");
        for key in [
            "MISE_DATA_DIR",
            "MISE_CONFIG_DIR",
            "MISE_STATE_DIR",
            "MISE_CACHE_DIR",
        ] {
            let dir = profile["environment"]["set_vars"][key].as_str().unwrap();
            assert!(dir.starts_with(&format!("{agent}/mise/")), "{key}={dir}");
        }
        assert!(profile.get("network").is_none(), "an install downloads");
    }

    /// A pool level writes its pool alone and reads its parents; it may
    /// take the token, which an agent's install may not, and a
    /// certificate path outside the system prefixes is readable.
    #[test]
    fn a_pool_install_profile_writes_only_its_pool() {
        let parents = [
            PathBuf::from("/p/fleet/mise"),
            PathBuf::from("/p/daemon/mise"),
        ];
        let call = pool_install_call(
            "crew payments/backend",
            Path::new("/p/crew/mise.toml"),
            Path::new("/p/crew/mise"),
            &parents,
            Path::new("/opt/mise/bin/mise"),
        );
        let env = InstallEnv::from_env(|k| (k == "SSL_CERT_FILE").then(|| "/opt/ca.pem".into()));
        let profile = call.profile(Path::new("/p/crew/.s/home"), &env);
        assert_eq!(
            profile["meta"]["name"],
            "balerix-mise-pool-crew-payments-backend"
        );
        assert_eq!(
            profile["filesystem"],
            serde_json::json!({
                "read": [
                    "/usr", "/lib", "/lib64", "/bin", "/etc",
                    "/opt/mise/bin/mise", "/p/crew/mise.toml",
                    "/p/fleet/mise", "/p/daemon/mise", "/opt/ca.pem",
                ],
                "allow": ["/p/crew/mise", "/p/crew/.s/home"],
            })
        );
        let allowed = profile["environment"]["allow_vars"].to_string();
        assert!(allowed.contains("GITHUB_TOKEN") && allowed.contains("HTTPS_PROXY"));
        let agent = agent_install_call(
            &id(),
            &StateLayout::from_env(Path::new("/h"), |_| None).agent(&id()),
            &StateLayout::from_env(Path::new("/h"), |_| None),
            Path::new("/m"),
        )
        .profile(Path::new("/s"), &env);
        assert!(
            !agent["environment"]["allow_vars"]
                .to_string()
                .contains("GITHUB_TOKEN")
        );
    }
