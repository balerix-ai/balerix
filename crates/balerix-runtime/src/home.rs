//! The agent's `$HOME` (Phase 2 spec §4.2 step 2): Claude settings with
//! balerix's hooks, credentials, a seeded `.claude.json`, gh hosts.

use std::os::fd::{AsFd, OwnedFd};
use std::path::Path;

pub use balerix_api::HOOK_EVENTS;
use balerix_api::{CredentialBundle, GitAuth, GitSettings};
use balerix_core::{AgentId, HookTarget, MaterializeError};
use serde_json::{Map, Value, json};

use crate::fsutil::{
    DirMode, ensure_dir, ensure_path_at, ensure_private_dir, open_dir_root, relative_to,
    write_atomic_at,
};
use crate::layout::AgentPaths;
use crate::quote::sh_quote;

/// Events Claude refuses to deliver over HTTP (verified against claude
/// 2.1.263: "HTTP hooks are not supported for SessionStart/Setup"); these
/// run `balerix hook-relay` as a `command` hook instead (P3-2).
pub const RELAY_EVENTS: &[&str] = &["SessionStart"];

pub const REDACTED: &str = "<redacted>";

/// User settings plus the balerix-owned `hooks` block. Any user `hooks` key
/// was rejected at validation; this overwrites unconditionally anyway.
pub fn render_settings(user: &Value, id: &AgentId, hooks: &HookTarget, relay: &Path) -> Value {
    let mut settings = match user {
        Value::Object(m) => m.clone(),
        _ => Map::new(),
    };
    let url = format!(
        "{}/v1/agents/{}/{}/{}/events",
        hooks.url.trim_end_matches('/'),
        id.fleet,
        id.crew,
        id.agent
    );
    let http = json!([{ "hooks": [{ "type": "http", "url": url, "headers": { "Authorization": format!("Bearer {}", hooks.secret) } }] }]);
    // The relay reads the URL and secret from its environment (set through
    // the nono profile), so this entry carries neither.
    let command = json!([{ "hooks": [{ "type": "command", "command": format!("{} hook-relay", sh_quote(&relay.display().to_string())), "timeout": 10 }] }]);
    let block: Map<String, Value> = HOOK_EVENTS
        .iter()
        .map(|e| {
            let entry = if RELAY_EVENTS.contains(e) {
                command.clone()
            } else {
                http.clone()
            };
            (e.to_string(), entry)
        })
        .collect();
    settings.insert("hooks".to_string(), Value::Object(block));
    Value::Object(settings)
}

/// `home/.gitconfig` (Phase 3 spec §6.3): identity always; the gh credential
/// helper only when the crew may push through gh. `gh` resolves through the
/// agent's mise shims inside the sandbox.
pub fn render_gitconfig(id: &AgentId, git: &GitSettings) -> String {
    let (name, email) = match &git.identity {
        Some(i) => (i.name.clone(), i.email.clone()),
        None => (
            id.to_string(),
            format!("{}@{}.{}.balerix.invalid", id.agent, id.crew, id.fleet),
        ),
    };
    let mut out =
        format!("# generated by balerix for {id}\n[user]\n\tname = {name}\n\temail = {email}\n");
    if git.auth == GitAuth::Gh && git.push {
        out.push_str("[credential]\n\thelper = \n\thelper = !gh auth git-credential\n");
    }
    out
}

pub fn render_hosts_yml(token: &str) -> String {
    format!("github.com:\n    oauth_token: {token}\n    git_protocol: https\n")
}

/// Seed that suppresses first-run prompts, overlaid with the account fields
/// the bundle carried (`oauthAccount`, `hasCompletedOnboarding`). `trusted`
/// are the directories whose "do you trust this folder?" dialog is
/// pre-accepted: the agent's workspace. Claude 2.1.263 keys the decision
/// on the common git dir, not on the cwd it asked about (verified by
/// hand, Phase 3 spec §8.1), which for a 0.1 worktree was the crew's
/// `repo/` and for a private clone (Spec N) is the workspace itself
/// (#74). Without it a fresh agent parks on that dialog and never sends
/// `SessionStart`.
///
/// `hasSeenAutoDefaultNudge` is the "No" to the one-time "Make auto mode
/// your default permission mode?" dialog claude 2.1.282 added, shown when
/// the user `settings.json` sets a `permissions.defaultMode` other than
/// `auto` (the host layer usually does) and no other settings file sets
/// `auto`. Declining it by hand under claude 2.1.283 wrote exactly this key
/// and nothing to `settings.json`; accepting writes `defaultMode: auto`
/// there instead. Like `hasCompletedOnboarding` it is an undocumented key
/// of claude's global config, so a `claude` bump re-checks it with
/// `mise run verify-claude` (#73).
pub fn render_claude_json(account: Option<&Value>, trusted: &[&Path]) -> Value {
    let mut m = Map::new();
    m.insert("hasCompletedOnboarding".to_string(), json!(true));
    m.insert("hasSeenAutoDefaultNudge".to_string(), json!(true));
    let projects: Map<String, Value> = trusted
        .iter()
        .map(|p| {
            (
                p.display().to_string(),
                json!({ "hasTrustDialogAccepted": true }),
            )
        })
        .collect();
    m.insert("projects".to_string(), Value::Object(projects));
    if let Some(Value::Object(a)) = account {
        for (k, v) in a {
            m.insert(k.clone(), v.clone());
        }
    }
    Value::Object(m)
}

pub struct HomeInputs<'a> {
    pub settings: &'a Value,
    pub creds: &'a CredentialBundle,
    pub hooks: &'a HookTarget,
    pub git: &'a GitSettings,
    pub relay: &'a Path,
    /// Directories whose trust dialog is pre-accepted in `.claude.json`.
    pub trusted: &'a [&'a Path],
    pub with_gh: bool,
    pub redact_credentials: bool,
}

fn io_err(id: &AgentId, path: &Path, e: std::io::Error) -> MaterializeError {
    MaterializeError::Io {
        id: id.to_string(),
        path: path.to_path_buf(),
        message: e.to_string(),
    }
}

/// Makes the agent's four mise directories (`AgentPaths::mise_dirs`) and
/// the data dir's `installs/`. They sit in `mise/` in the agent root,
/// which the daemon alone writes, so the four are made by path; the agent
/// can write inside them, so `installs/` is reached by descriptor and a
/// link or file found in its place is replaced by a real directory. The
/// daemon's install (`Toolchain::install`) calls it just before mise
/// runs; its sandbox is what holds if the agent replaces something after
/// this.
pub(crate) fn ensure_mise_dirs(id: &AgentId, paths: &AgentPaths) -> Result<(), MaterializeError> {
    for d in paths.mise_dirs() {
        ensure_dir(&d).map_err(|e| io_err(id, &d, e))?;
    }
    let data = paths.mise_data_dir();
    let dir = open_dir_root(&data, DirMode::Default).map_err(|e| io_err(id, &data, e))?;
    crate::fsutil::ensure_dir_at(dir.as_fd(), "installs", DirMode::Default)
        .map(drop)
        .map_err(|e| io_err(id, &data.join("installs"), e))
}

/// Writes the agent's home. `root`, `logs` and nono's home are balerix's
/// own; everything under `home/` is written without following a link
/// below `home/` itself: `home/` is opened once, each directory beneath it
/// is reached by descriptor (a link or file found in its place is
/// replaced by a real directory), modes are set through descriptors, and
/// each file is a temp file renamed into place in its directory
/// (`fsutil::write_atomic_at`).
pub fn write_home(
    id: &AgentId,
    paths: &AgentPaths,
    inputs: &HomeInputs,
) -> Result<(), MaterializeError> {
    // The agent root, its home and its logs hold secrets (settings.json,
    // .credentials.json, hosts.yml) and transcripts: 0700, no group or
    // other access. The rest are ordinary tool directories.
    // `tmp/` is 0700 too: claude checks its temp dir's mode before using it.
    for d in [&paths.root, &paths.logs] {
        ensure_private_dir(d).map_err(|e| io_err(id, d, e))?;
    }
    ensure_dir(&paths.nono_home).map_err(|e| io_err(id, &paths.nono_home, e))?;
    let home =
        open_dir_root(&paths.home, DirMode::Private).map_err(|e| io_err(id, &paths.home, e))?;
    let sub = |path: &Path, mode: DirMode| {
        relative_to(&paths.home, path)
            .and_then(|rel| ensure_path_at(home.as_fd(), rel, mode))
            .map_err(|e| io_err(id, path, e))
    };
    let claude_dir = paths.claude_dir();
    let claude = sub(&claude_dir, DirMode::Private)?;
    sub(&paths.tmp_dir(), DirMode::Private)?;
    let gh_dir = paths.gh_dir();
    let gh = sub(&gh_dir, DirMode::Default)?;
    for d in [paths.xdg_data(), paths.xdg_state(), paths.xdg_cache()] {
        sub(&d, DirMode::Default)?;
    }
    // the agent's sandbox grants them, and nono grants only what exists
    ensure_mise_dirs(id, paths)?;
    let pretty = |v: &Value| serde_json::to_vec_pretty(v).unwrap_or_default();
    let write = |dir: &OwnedFd, at: &Path, name: &str, contents: &[u8]| {
        write_atomic_at(dir.as_fd(), name, contents, 0o600)
            .map_err(|e| io_err(id, &at.join(name), e))
    };

    // 0600: the hooks block carries the per-agent bearer secret.
    write(
        &claude,
        &claude_dir,
        "settings.json",
        &pretty(&render_settings(
            inputs.settings,
            id,
            inputs.hooks,
            inputs.relay,
        )),
    )?;

    match (&inputs.creds.claude_credentials, inputs.redact_credentials) {
        (Some(_), true) => write(
            &claude,
            &claude_dir,
            ".credentials.json",
            &pretty(&json!(REDACTED)),
        )?,
        (Some(c), false) => write(&claude, &claude_dir, ".credentials.json", &pretty(c))?,
        (None, _) => {}
    }

    // Claude Code reads `$CLAUDE_CONFIG_DIR/.claude.json` when that variable
    // is set, and the sandbox profile sets it; verified by hand with claude
    // 2.1.263 (only this copy was ever rewritten), so the `$HOME` copy that
    // Phase 2 also wrote is gone.
    write(
        &claude,
        &claude_dir,
        ".claude.json",
        &pretty(&render_claude_json(
            inputs.creds.claude_account.as_ref(),
            inputs.trusted,
        )),
    )?;

    if inputs.with_gh
        && let Some(token) = &inputs.creds.gh_token
    {
        let token = if inputs.redact_credentials {
            REDACTED
        } else {
            token.as_str()
        };
        write(
            &gh,
            &gh_dir,
            "hosts.yml",
            render_hosts_yml(token).as_bytes(),
        )?;
    }

    // 0600 like the rest of home/: it names the credential helper.
    write(
        &home,
        &paths.home,
        ".gitconfig",
        render_gitconfig(id, inputs.git).as_bytes(),
    )?;
    Ok(())
}

